  CREATE OR REPLACE FUNCTION "GET_IDCONVERSIONUNIT_FROM_IDUNITS_IDRESOURCE" (pIdInitalUnit RAW, pIdFinalUnit RAW, pIdResource RAW)
RETURN RAW
IS
    id_ RAW(16);
BEGIN
    If pIdResource IS NULL THEN
        SELECT idConversionUnit INTO id_ FROM tbConversionUnits WHERE idInitialUnit = pIdInitalUnit AND idFinalUnit = pIdFinalUnit AND idResource IS NULL;
    ELSE
        SELECT idConversionUnit INTO id_ FROM tbConversionUnits WHERE idInitialUnit = pIdInitalUnit AND idFinalUnit = pIdFinalUnit AND idResource = pIdResource;
    END IF;
    RETURN id_;
END;
