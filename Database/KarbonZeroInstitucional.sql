   COMMENT ON COLUMN "TBCONSUMPTIONS"."IDRESOURCEPURITY" IS 'Identificador único de la presentación del recurso';
   COMMENT ON COLUMN "TBCONSUMPTIONS"."IDUSER" IS 'Identificador único del usuario que realizó el consumo';
   COMMENT ON COLUMN "TBCONSUMPTIONS"."QUANTITY" IS 'La cantidad de recurso que ha sido consumida en términos de su unidad de medida';
   COMMENT ON COLUMN "TBCONSUMPTIONS"."CONSUMPTIONDATE" IS 'La fecha en que se consumió el recurso';
   COMMENT ON COLUMN "TBCONSUMPTIONS"."COST" IS 'Costo del consumo en dólares';

   COMMENT ON COLUMN "TBCONVERSIONUNITS"."IDCONVERSIONUNIT" IS 'Identificador único de la operación de conversión.';
   COMMENT ON COLUMN "TBCONVERSIONUNITS"."IDINITIALUNIT" IS 'Identificador único de la unidad de medida antes de la conversión';
   COMMENT ON COLUMN "TBCONVERSIONUNITS"."IDFINALUNIT" IS 'Identificador único de la unidad de medida posterior a la conversión';
   COMMENT ON COLUMN "TBCONVERSIONUNITS"."IDRESOURCE" IS 'Identificador único del recurso (si es nulo la conversión es aplicable universalmente)';
   COMMENT ON COLUMN "TBCONVERSIONUNITS"."OPERATION" IS 'Operación que se debe realizar para efectuar la conversión (suma o producto)';
   COMMENT ON COLUMN "TBCONVERSIONUNITS"."CONSTANT" IS 'Constante numérica para llevar a cabo la conversión';

   COMMENT ON COLUMN "TBMEASURES"."IDMEASURE" IS 'Identificador único de la medida';
   COMMENT ON COLUMN "TBMEASURES"."NAME" IS 'Nombre de la medida';

   COMMENT ON COLUMN "TBMEASUREUNITS"."IDMEASUREUNIT" IS 'Identificador único de la unidad de medida';
   COMMENT ON COLUMN "TBMEASUREUNITS"."IDMEASURE" IS 'Identificador único de la medida';
   COMMENT ON COLUMN "TBMEASUREUNITS"."NAME" IS 'Nombre de la unidad de medida';

   COMMENT ON COLUMN "TBRESOURCEPURITIES"."IDRESOURCEPURITY" IS 'Identificador único de la presentación del recurso';
   COMMENT ON COLUMN "TBRESOURCEPURITIES"."IDRESOURCE" IS 'Identificador único del recurso';
   COMMENT ON COLUMN "TBRESOURCEPURITIES"."PURITY" IS 'Porcentaje de pureza del recurso (siendo 1 completamente puro)';

   COMMENT ON COLUMN "TBRESOURCES"."IDRESOURCE" IS 'Identificador único del recurso';
