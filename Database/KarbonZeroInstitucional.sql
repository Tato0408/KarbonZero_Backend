  CREATE OR REPLACE PROCEDURE "INVERSE_CONVERSION_UNIT" (pIdConversionUnit RAW)
IS
    idMeasureUnit RAW(16);
    idMeasureUnitFinal RAW(16);
    idResource_ RAW(16);
    operation VARCHAR2(100);
    new_operation VARCHAR2(100);
    constant NUMBER;
    count_ NUMBER;
BEGIN

    SELECT idInitialUnit INTO idMeasureUnit FROM tbConversionUnits WHERE idConversionUnit = pIdConversionUnit;
    SELECT idFinalUnit INTO idMeasureUnitFinal FROM tbConversionUnits WHERE idConversionUnit = pIdConversionUnit;
    SELECT idResource INTO idResource_ FROM tbConversionUnits WHERE idConversionUnit = pIdConversionUnit;
    SELECT operation INTO operation FROM tbConversionUnits WHERE idConversionUnit = pIdConversionUnit;
    SELECT constant INTO constant FROM tbConversionUnits WHERE idConversionUnit = pIdConversionUnit;

    IF operation = 'SUM' THEN
        new_operation := 'SUST';
    ELSIF operation = 'SUST' THEN
        new_operation := 'SUM';
    ELSIF operation = 'PROD' THEN
        new_operation := 'DIV';
    ELSE
        new_operation := 'PROD';
    END IF;

    SELECT COUNT(*) INTO count_ FROM tbConversionUnits WHERE idInitialUnit = idMeasureUnitFinal AND idFinalUnit = idMeasureUnit AND idResource = idResource_;

    IF count_ = 0 THEN
        INSERT INTO tbConversionUnits VALUES (SYS_GUID(), idMeasureUnitFinal, idMeasureUnit, idResource_, new_operation, constant);
    END IF;
END;
