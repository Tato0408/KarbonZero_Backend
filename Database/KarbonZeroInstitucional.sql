-- =============================================================================================
-- 1. TABLAS
-- =============================================================================================

  CREATE TABLE "TBCONSUMPTIONS"
   (	"IDCONSUMPTION" RAW(16),
	"IDRESOURCEPURITY" RAW(16) NOT NULL ENABLE,
	"IDUSER" RAW(16) NOT NULL ENABLE,
	"QUANTITY" NUMBER NOT NULL ENABLE,
	"CONSUMPTIONDATE" DATE NOT NULL ENABLE,
	"COST" NUMBER NOT NULL ENABLE,
	 CHECK (quantity > 0) ENABLE,
	 CHECK (cost > 0) ENABLE,
	 PRIMARY KEY ("IDCONSUMPTION")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBCONVERSIONUNITS"
   (	"IDCONVERSIONUNIT" RAW(16),
	"IDINITIALUNIT" RAW(16) NOT NULL ENABLE,
	"IDFINALUNIT" RAW(16) NOT NULL ENABLE,
	"IDRESOURCE" RAW(16),
	"OPERATION" VARCHAR2(100) NOT NULL ENABLE,
	"CONSTANT" NUMBER NOT NULL ENABLE,
	 PRIMARY KEY ("IDCONVERSIONUNIT")
  USING INDEX  ENABLE,
	 UNIQUE ("IDINITIALUNIT", "IDFINALUNIT", "IDRESOURCE")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBMEASURES"
   (	"IDMEASURE" RAW(16),
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	 PRIMARY KEY ("IDMEASURE")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBMEASUREUNITS"
   (	"IDMEASUREUNIT" RAW(16),
	"IDMEASURE" RAW(16) NOT NULL ENABLE,
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	 PRIMARY KEY ("IDMEASUREUNIT")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBRESOURCEPURITIES"
   (	"IDRESOURCEPURITY" RAW(16),
	"IDRESOURCE" RAW(16) NOT NULL ENABLE,
	"PURITY" NUMBER(5,2) DEFAULT 1 NOT NULL ENABLE,
	 CHECK (purity > 0 AND purity <= 1) ENABLE,
	 PRIMARY KEY ("IDRESOURCEPURITY")
  USING INDEX  ENABLE,
	 UNIQUE ("IDRESOURCE", "PURITY")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBRESOURCES"
   (	"IDRESOURCE" RAW(16),
	"IDMEASUREUNIT" RAW(16) NOT NULL ENABLE,
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	"CARBONFOOTPRINT" NUMBER NOT NULL ENABLE,
	 CHECK (carbonFootprint > 0) ENABLE,
	 PRIMARY KEY ("IDRESOURCE")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBROLS"
   (	"IDROL" RAW(16),
	"NAME" VARCHAR2(100) NOT NULL ENABLE,
	"STATUS" NUMBER(3,0) NOT NULL ENABLE,
	 PRIMARY KEY ("IDROL")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBUSERS"
   (	"IDUSER" RAW(16),
	"IDROL" RAW(16) NOT NULL ENABLE,
	"USERNAME" VARCHAR2(200) NOT NULL ENABLE,
	"FIRSTNAME" VARCHAR2(200),
	"LASTNAME" VARCHAR2(200),
	"EMAIL" VARCHAR2(200) NOT NULL ENABLE,
	"USERPASSWORD" VARCHAR2(200) NOT NULL ENABLE,
	"IMAGEPATH" VARCHAR2(200),
	"DISABLED" NUMBER(1,0) DEFAULT 0 NOT NULL ENABLE,
	 PRIMARY KEY ("IDUSER")
  USING INDEX  ENABLE,
	 UNIQUE ("USERNAME")
  USING INDEX  ENABLE,
	 UNIQUE ("EMAIL")
  USING INDEX  ENABLE
   ) ;

